"""SQLite migration integration tests.

Tests that Alembic migrations work correctly with SQLite, ensuring
dialect-aware compatibility (UUID, JSON, timestamp defaults).
"""
import os
from pathlib import Path
from unittest.mock import patch

import pytest
from alembic.config import Config
from sqlalchemy import create_engine, text

from alembic import command


@pytest.fixture(scope="module")
def sqlite_db_path(tmp_path_factory: pytest.TempPathFactory) -> str:
    """Create a temporary SQLite database file for migration testing."""
    db_file = tmp_path_factory.mktemp("sqlite_test") / "test.db"
    yield str(db_file)
    # Cleanup
    if os.path.exists(db_file):
        os.unlink(db_file)


@pytest.fixture(autouse=True)
def _reset_settings_cache() -> None:
    """Reset settings cache before each test to pick up DATABASE_URL."""
    from app.core.config import get_settings
    get_settings.cache_clear()
    yield
    get_settings.cache_clear()


class TestSQLiteMigration:
    """Test SQLite compatibility of Alembic migrations."""

    def test_migration_runs_on_sqlite(self, sqlite_db_path: str) -> None:
        """Test that Alembic upgrade works on SQLite."""
        # Set DATABASE_URL so env.py picks it up via get_settings()
        with patch.dict(os.environ, {"DATABASE_URL": f"sqlite+aiosqlite:///{sqlite_db_path}"}):
            from app.core.config import get_settings
            get_settings.cache_clear()  # Reset to pick up new env var

            alembic_cfg = Config()
            alembic_cfg.set_main_option(
                "sqlalchemy.url", f"sqlite+aiosqlite:///{sqlite_db_path}"
            )
            alembic_cfg.set_main_option(
                "script_location",
                str(Path(__file__).parent.parent.parent / "alembic"),
            )

            # This should not raise an exception
            command.upgrade(alembic_cfg, "head")

    def test_timestamp_defaults_work(self, sqlite_db_path: str) -> None:
        """Test that CURRENT_TIMESTAMP default works in SQLite."""
        with patch.dict(os.environ, {"DATABASE_URL": f"sqlite+aiosqlite:///{sqlite_db_path}"}):
            from app.core.config import get_settings
            get_settings.cache_clear()

            # First run migration
            alembic_cfg = Config()
            alembic_cfg.set_main_option(
                "sqlalchemy.url", f"sqlite+aiosqlite:///{sqlite_db_path}"
            )
            alembic_cfg.set_main_option(
                "script_location",
                str(Path(__file__).parent.parent.parent / "alembic"),
            )
            command.upgrade(alembic_cfg, "head")

        # Now test inserting without explicit timestamps
        engine = create_engine(f"sqlite:///{sqlite_db_path}", echo=False)
        with engine.begin() as conn:
            conn.execute(
                text(
                    'INSERT INTO users (id, email) VALUES '
                    '("123e4567-e89b-12d3-a456-426614174000", "test@example.com")'
                )
            )
            row = conn.execute(
                text("SELECT created_at, updated_at FROM users WHERE email = 'test@example.com'")
            ).fetchone()

            # Timestamps should be auto-generated by CURRENT_TIMESTAMP default
            assert row is not None
            assert row[0] is not None, "created_at should not be NULL"
            assert row[1] is not None, "updated_at should not be NULL"

        engine.dispose()

    def test_json_columns_work(self, sqlite_db_path: str) -> None:
        """Test that JSON columns work in SQLite (stored as TEXT)."""
        with patch.dict(os.environ, {"DATABASE_URL": f"sqlite+aiosqlite:///{sqlite_db_path}"}):
            from app.core.config import get_settings
            get_settings.cache_clear()

            # First run migration
            alembic_cfg = Config()
            alembic_cfg.set_main_option(
                "sqlalchemy.url", f"sqlite+aiosqlite:///{sqlite_db_path}"
            )
            alembic_cfg.set_main_option(
                "script_location",
                str(Path(__file__).parent.parent.parent / "alembic"),
            )
            command.upgrade(alembic_cfg, "head")

        # Test JSON read/write
        engine = create_engine(f"sqlite:///{sqlite_db_path}", echo=False)
        with engine.begin() as conn:
            conn.execute(
                text(
                    'INSERT INTO users (id, email, metadata) VALUES '
                    '("223e4567-e89b-12d3-a456-426614174001", "test2@example.com", \'{"key": "value"}\')'
                )
            )
            row = conn.execute(
                text("SELECT metadata FROM users WHERE email = 'test2@example.com'")
            ).fetchone()

            assert row is not None
            # JSON is stored as TEXT in SQLite, but should be readable
            assert row[0] == '{"key": "value"}'

        engine.dispose()
